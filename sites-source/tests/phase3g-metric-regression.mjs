import assert from 'node:assert/strict';
import * as metric from '../scripts/leakage-metrics.mjs';
assert.equal(typeof metric.alignedMarkerBoxes, 'function', 'marker geometry must use a common first-line window');
const cells = [0,1,2,3,4].map(i=>({x:.2+(i===4?.002:0),y:.1+i*.02,w:.3,h:i===4?.08:.02}));
const boxes=metric.alignedMarkerBoxes(cells,.03);
assert.equal(boxes[4].h,boxes[0].h,'E trailing whitespace must not dilute marker density');
assert.equal(boxes[4].x,cells[4].x,'shifted markers must retain their own x anchor');
assert.equal(metric.alignedMarkerBoxes([null,...cells.slice(1)],.03)[0],null);
const rows=Array.from({length:12},(_,n)=>({number:n+1,options:[.11,.15,.09,.17,.06].map(value=>({value:value+n*.0001}))}));
const normalized=metric.normalizeByPosition(rows,1,'value');
assert.equal(normalized.status,'measured');
assert.ok(Math.max(...normalized.values)-Math.min(...normalized.values)<1e-10,'intrinsic letter/position darkness must cancel');
rows[0].options[4].value+=.05;
const changed=metric.normalizeByPosition(rows,1,'value');
assert.ok(changed.values[4]>.049,'held-out anomaly must not contaminate its baseline');
assert.equal(metric.normalizeByPosition(rows.slice(0,3),1,'value').status,'insufficient-baseline');
rows[0].options[2]=null;
assert.equal(metric.normalizeByPosition(rows,1,'value').status,'insufficient-option-geometry');
console.log('phase3g metric regression: passed (E geometry, shifted anchor, letter baseline, leave-one-out, small sample, unknown geometry)');
